const {chromium} = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
  const page = await browser.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8769/');
  await page.waitForFunction(() => document.querySelector('#snap').textContent.includes('UI build'));
  await page.locator('#find').fill('CA5100107');
  await page.locator('#find').dispatchEvent('change');
  await page.locator('#detail details.grp > summary').click();
  assert.ok((await page.locator('#detail').innerText()).includes('$8.0M'));
  await page.locator('[data-project="centralized"]').check();
  await page.locator('#applyProject').click();
  await page.waitForFunction(() => location.hash.includes('projects='));
  assert.ok((await page.locator('#detail').innerText()).includes('$1.2M'));
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#syslist').children.length > 0);
  await page.locator('#find').fill('CA5100107');
  await page.locator('#find').dispatchEvent('change');
  assert.ok((await page.locator('#detail').innerText()).includes('$1.2M'));
  await page.locator('#detail details.grp > summary').click();
  await page.locator('#clearProject').click();
  await page.waitForFunction(() => !location.hash.includes('projects='));
  assert.ok((await page.locator('#detail').innerText()).includes('$8.0M'));
  await page.locator('[data-tab="method"]').click();
  assert.ok((await page.locator('#tabbody').innerText()).includes('Colfax'));
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: published budget, scope change, shared URL reload, reset, source catalog; no page errors');
})().catch(e => {console.error(e); process.exit(1);});
